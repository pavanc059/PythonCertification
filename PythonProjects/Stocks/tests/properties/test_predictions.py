class TestProperty16LowConfidenceFlagging:
    """
    **Validates: Requirement 3.12**
    
    Property 16: For any prediction, when the confidence score is below 60%,
    the system SHALL flag the prediction as low-confidence.
    """
    
    @given(
        confidence=st.floats(min_value=0.0, max_value=59.99)
    )
    @settings(max_examples=30, deadline=None)
    def test_property_16_low_confidence_flagged(self, confidence):
        """
        **Validates: Requirement 3.12**
        
        Verify that predictions with confidence < 60% are flagged.
        """
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=confidence,
            lower_bound=90.0,
            upper_bound=110.0
        )
        
        # Property 16: Low confidence flag must be True for confidence < 60
        assert pred.low_confidence is True, \
            f"Expected low_confidence=True for confidence={confidence}"
    
    @given(
        confidence=st.floats(min_value=60.0, max_value=100.0)
    )
    @settings(max_examples=30, deadline=None)
    def test_property_16_high_confidence_not_flagged(self, confidence):
        """
        **Validates: Requirement 3.12**
        
        Verify that predictions with confidence >= 60% are NOT flagged.
        """
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=confidence,
            lower_bound=90.0,
            upper_bound=110.0
        )
        
        # Property 16: Low confidence flag must be False for confidence >= 60
        assert pred.low_confidence is False, \
            f"Expected low_confidence=False for confidence={confidence}"
    
    def test_property_16_boundary_at_60(self):
        """Edge case: Exactly 60% confidence is NOT flagged as low."""
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=60.0,
            lower_bound=90.0,
            upper_bound=110.0
        )
        assert pred.low_confidence is False
    
    def test_property_16_just_below_threshold(self):
        """Edge case: 59.99% confidence IS flagged as low."""
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=59.99,
            lower_bound=90.0,
            upper_bound=110.0
        )
        assert pred.low_confidence is True


