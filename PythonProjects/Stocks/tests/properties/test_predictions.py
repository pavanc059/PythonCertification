@st.composite
def prediction_value_with_bounds(draw):
    """
    Generate a valid prediction value with lower and upper bounds.
    
    Ensures: lower_bound <= value <= upper_bound
    
    Returns:
        Tuple of (value, lower_bound, upper_bound)
    """
    # Generate value in reasonable range for stock predictions
    value = draw(st.floats(
        min_value=-100.0,
        max_value=1000.0,
        allow_nan=False,
        allow_infinity=False
    ))
    
    # Generate bounds around the value
    # Lower bound is below value
    lower_offset = draw(st.floats(min_value=0.0, max_value=50.0))
    lower_bound = value - abs(lower_offset)
    
    # Upper bound is above value
    upper_offset = draw(st.floats(min_value=0.0, max_value=50.0))
    upper_bound = value + abs(upper_offset)
    
    return value, lower_bound, upper_bound


@st.composite
def valid_prediction(draw, prediction_type=None):
    """
    Generate a valid Prediction object with all constraints satisfied.
    
    Args:
        prediction_type: Optional fixed prediction type
    
    Returns:
        Prediction object
    """
    ticker = draw(st.text(
        alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        min_size=1,
        max_size=5
    ))
    
    pred_type = prediction_type or draw(st.sampled_from([
        'price', 'direction', 'return'
    ]))
    
    # Generate value with proper bounds
    value, lower_bound, upper_bound = draw(prediction_value_with_bounds())
    
    # Confidence in [0, 100]
    confidence = draw(st.floats(min_value=0.0, max_value=100.0))
    
    # Generate factors (SHAP values)
    num_factors = draw(st.integers(min_value=0, max_value=5))
    factors = {}
    if num_factors > 0:
        factor_names = ['technical', 'fundamental', 'sentiment', 'volume', 'momentum']
        for i in range(num_factors):
            factors[factor_names[i]] = draw(st.floats(
                min_value=-1.0, max_value=1.0,
                allow_nan=False, allow_infinity=False
            ))
    
    # Create prediction
    return Prediction(
        ticker=ticker,
        timestamp=datetime.now(),
        prediction_type=pred_type,
        value=value,
        confidence=confidence,
        lower_bound=lower_bound,
        upper_bound=upper_bound,
        factors=factors,
        model='ensemble'
    )


@st.composite
def prediction_list(draw, min_size=0, max_size=50):
    """
    Generate a list of valid Prediction objects.
    
    Args:
        min_size: Minimum number of predictions
        max_size: Maximum number of predictions
    
    Returns:
        List of Prediction objects
    """
    size = draw(st.integers(min_value=min_size, max_value=max_size))
    predictions = []
    
    for _ in range(size):
        pred = draw(valid_prediction())
        predictions.append(pred)
    
    return predictions


