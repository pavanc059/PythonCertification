class TestProperty13ConfidenceRange:
    """
    **Validates: Requirement 3.3, 13.4**
    
    Property 13: For any prediction generated by the system, the confidence
    score SHALL be in the range [0, 100], representing a percentage.
    """
    
    @given(pred=valid_prediction())
    @settings(max_examples=50, deadline=None)
    def test_property_13_confidence_in_valid_range(self, pred):
        """
        **Validates: Requirement 3.3**
        
        Verify that all prediction confidence scores are in [0, 100].
        """
        # Property 13: Confidence must be in [0, 100]
        assert 0.0 <= pred.confidence <= 100.0, \
            f"Confidence {pred.confidence} not in [0, 100]"
    
    @given(
        confidence=st.floats(
            min_value=-1000.0,
            max_value=-0.01,
            allow_nan=False,
            allow_infinity=False
        )
    )
    @settings(max_examples=20, deadline=None)
    def test_property_13_negative_confidence_raises_error(self, confidence):
        """
        **Validates: Requirement 3.3**
        
        Verify that negative confidence values raise ValueError.
        """
        with pytest.raises(ValueError, match="Property 13 violation"):
            Prediction(
                ticker="TEST",
                timestamp=datetime.now(),
                prediction_type='price',
                value=100.0,
                confidence=confidence,
                lower_bound=95.0,
                upper_bound=105.0
            )
    
    @given(
        confidence=st.floats(
            min_value=100.01,
            max_value=10000.0,
            allow_nan=False,
            allow_infinity=False
        )
    )
    @settings(max_examples=20, deadline=None)
    def test_property_13_excessive_confidence_raises_error(self, confidence):
        """
        **Validates: Requirement 3.3**
        
        Verify that confidence > 100 raises ValueError.
        """
        with pytest.raises(ValueError, match="Property 13 violation"):
            Prediction(
                ticker="TEST",
                timestamp=datetime.now(),
                prediction_type='price',
                value=100.0,
                confidence=confidence,
                lower_bound=95.0,
                upper_bound=105.0
            )
    
    def test_property_13_boundary_values(self):
        """Edge case: Confidence at exact boundaries (0 and 100)."""
        # Confidence = 0
        pred_min = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=0.0,
            lower_bound=95.0,
            upper_bound=105.0
        )
        assert pred_min.confidence == 0.0
        
        # Confidence = 100
        pred_max = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=100.0,
            lower_bound=95.0,
            upper_bound=105.0
        )
        assert pred_max.confidence == 100.0


