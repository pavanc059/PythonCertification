# Property 15: Prediction Bounds Consistency
# ===========================================================================

class TestProperty15BoundsConsistency:
    """
    **Validates: Requirement 3.5, 13.4**
    
    Property 15: For any prediction with uncertainty quantification, the
    system SHALL satisfy: lower_bound ≤ predicted_value ≤ upper_bound.
    """
    
    @given(pred=valid_prediction())
    @settings(max_examples=50, deadline=None)
    def test_property_15_bounds_ordering(self, pred):
        """
        **Validates: Requirement 3.5**
        
        Verify that bounds are properly ordered around prediction value.
        """
        # Property 15: Bounds consistency
        assert pred.lower_bound <= pred.value <= pred.upper_bound, \
            f"Bounds violation: {pred.lower_bound} ≤ {pred.value} ≤ {pred.upper_bound}"
    
    @given(
        value=st.floats(min_value=50.0, max_value=150.0, allow_nan=False, allow_infinity=False),
        lower_offset=st.floats(min_value=0.1, max_value=20.0),
        upper_offset=st.floats(min_value=0.1, max_value=20.0)
    )
    @settings(max_examples=30, deadline=None)
    def test_property_15_valid_bounds_construction(self, value, lower_offset, upper_offset):
        """
        **Validates: Requirement 3.5**
        
        Verify that properly constructed bounds pass validation.
        """
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=value,
            confidence=70.0,
            lower_bound=value - abs(lower_offset),
            upper_bound=value + abs(upper_offset)
        )
        
        assert pred.lower_bound <= pred.value <= pred.upper_bound
    
    def test_property_15_inverted_bounds_raises_error(self):
        """
        **Validates: Requirement 3.5**
        
        Edge case: Inverted bounds (lower > upper) should raise ValueError.
        """
        with pytest.raises(ValueError, match="Property 15 violation"):
            Prediction(
                ticker="TEST",
                timestamp=datetime.now(),
                prediction_type='price',
                value=100.0,
                confidence=70.0,
                lower_bound=105.0,  # Lower bound > value
                upper_bound=95.0    # Upper bound < value
            )
    
    def test_property_15_value_below_lower_bound_raises_error(self):
        """Edge case: Value below lower bound raises ValueError."""
        with pytest.raises(ValueError, match="Property 15 violation"):
            Prediction(
                ticker="TEST",
                timestamp=datetime.now(),
                prediction_type='price',
                value=90.0,
                confidence=70.0,
                lower_bound=100.0,  # Lower bound > value
                upper_bound=110.0
            )
    
    def test_property_15_value_above_upper_bound_raises_error(self):
        """Edge case: Value above upper bound raises ValueError."""
        with pytest.raises(ValueError, match="Property 15 violation"):
            Prediction(
                ticker="TEST",
                timestamp=datetime.now(),
                prediction_type='price',
                value=120.0,
                confidence=70.0,
                lower_bound=100.0,
                upper_bound=110.0  # Upper bound < value
            )
    
    def test_property_15_equal_bounds_allowed(self):
        """Edge case: Value can equal bounds (point prediction)."""
        # Value equals lower bound
        pred1 = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=90.0,
            lower_bound=100.0,
            upper_bound=105.0
        )
        assert pred1.value == pred1.lower_bound
        
        # Value equals upper bound
        pred2 = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=105.0,
            confidence=90.0,
            lower_bound=100.0,
            upper_bound=105.0
        )
        assert pred2.value == pred2.upper_bound
        
        # All three equal (point prediction with no uncertainty)
        pred3 = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='price',
            value=100.0,
            confidence=100.0,
            lower_bound=100.0,
            upper_bound=100.0
        )
        assert pred3.lower_bound == pred3.value == pred3.upper_bound


