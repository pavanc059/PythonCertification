class TestProperty14CategoryAssignment:
    """
    **Validates: Requirement 3.4**
    
    Property 14: For any prediction, the system SHALL assign exactly one
    category from the valid set: Strong Buy, Buy, Hold, Sell, Strong Sell.
    """
    
    VALID_CATEGORIES = {'Strong Buy', 'Buy', 'Hold', 'Sell', 'Strong Sell'}
    
    @given(pred=valid_prediction())
    @settings(max_examples=50, deadline=None)
    def test_property_14_valid_category_assigned(self, pred):
        """
        **Validates: Requirement 3.4**
        
        Verify that every prediction has a valid category.
        """
        # Property 14: Category must be one of the valid values
        assert pred.category in self.VALID_CATEGORIES, \
            f"Invalid category '{pred.category}'"
    
    @given(pred=valid_prediction(prediction_type='return'))
    @settings(max_examples=50, deadline=None)
    def test_property_14_category_consistency_with_value(self, pred):
        """
        **Validates: Requirement 3.4**
        
        Verify that category assignment is consistent with prediction value.
        """
        return_pct = pred.value * 100
        
        if pred.category == 'Strong Buy':
            # Strong Buy requires high positive return and high confidence
            assert return_pct > 5.0 and pred.confidence > 70.0, \
                f"Strong Buy with return {return_pct}% and confidence {pred.confidence}%"
        
        elif pred.category == 'Strong Sell':
            # Strong Sell requires high negative return and high confidence
            assert return_pct < -5.0 and pred.confidence > 70.0, \
                f"Strong Sell with return {return_pct}% and confidence {pred.confidence}%"
        
        elif pred.category == 'Buy':
            # Buy requires positive return
            assert return_pct > -2.0, \
                f"Buy category with negative return {return_pct}%"
        
        elif pred.category == 'Sell':
            # Sell requires negative return
            assert return_pct < 2.0, \
                f"Sell category with positive return {return_pct}%"
    
    def test_property_14_strong_buy_conditions(self):
        """Integration test: Strong Buy requires high return + high confidence."""
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='return',
            value=0.08,  # 8% return
            confidence=75.0,
            lower_bound=0.05,
            upper_bound=0.11
        )
        assert pred.category == 'Strong Buy'
    
    def test_property_14_strong_sell_conditions(self):
        """Integration test: Strong Sell requires high loss + high confidence."""
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='return',
            value=-0.08,  # -8% return
            confidence=75.0,
            lower_bound=-0.11,
            upper_bound=-0.05
        )
        assert pred.category == 'Strong Sell'
    
    def test_property_14_hold_for_small_changes(self):
        """Integration test: Hold assigned for small changes."""
        pred = Prediction(
            ticker="TEST",
            timestamp=datetime.now(),
            prediction_type='return',
            value=0.01,  # 1% return (small)
            confidence=50.0,
            lower_bound=-0.02,
            upper_bound=0.04
        )
        assert pred.category == 'Hold'


